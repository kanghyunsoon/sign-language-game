/**
 * 인식이 한동안 안 될 때 카메라 위에 띄우는 글자별 자세 팁.
 *
 * 대상은 인식기가 구조적으로 약한 글자들이다.
 *
 * - ㅓ·ㅕ·ㅔ·ㅖ: 손끝이 카메라를 향해 손가락이 서로를 가리고 랜드마크가
 *   흔들린다. 손등이 살짝 보이게 기울이면 손가락 개수가 드러나 안정된다.
 * - ㅅ↔ㅠ, ㄹ↔ㅌ: 랜드마크가 거의 같은 혼동쌍. 구분점(손목 꺾기,
 *   손가락 붙임/벌림)을 사용자가 명확히 만들어야 한다.
 * - ㅂ·ㅎ: 게으른 자세(벌린 손, 그냥 주먹)는 서버가 억제하므로, 정확한
 *   자세를 다시 안내한다.
 *
 * 글자 카드의 설명문에도 같은 내용이 있지만, 플레이 중에는 시선이 카메라에
 * 가 있어 잘 읽히지 않는다는 피드백에 따라 카메라 위 배너로도 보여준다.
 */
const RECOGNITION_TIPS: Readonly<Record<string, string>> = {
  ㅓ: "손등이 살짝 보이게 손목을 돌려보세요.",
  ㅕ: "손등이 살짝 보이게 손목을 돌려보세요.",
  ㅔ: "손등이 살짝 보이게 손목을 돌려보세요.",
  ㅖ: "손등이 살짝 보이게 손목을 돌려보세요.",
  ㅅ: "손목을 살짝 꺾어 손끝을 비스듬히 내려보세요.",
  ㄹ: "세 손가락 사이를 살짝 벌려보세요.",
  ㅌ: "세 손가락을 서로 붙여보세요.",
  ㅂ: "엄지를 손바닥 위로 확실히 접고 네 손가락을 모아 펴보세요.",
  ㅎ: "주먹을 쥐고 엄지만 위로 곧게 세워보세요.",
};

/** 글자에 등록된 인식 팁. 없으면 undefined — 배너를 띄우지 않는다. */
export function findRecognitionTip(symbol: string): string | undefined {
  return RECOGNITION_TIPS[symbol];
}
